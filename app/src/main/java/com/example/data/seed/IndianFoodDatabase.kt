    fun searchFoods(query: String, region: IndianRegion? = null, dietaryType: DietaryType? = null): List<IndianFoodItem> {
        val cleanQuery = query.trim().lowercase()
        return allFoods.filter { food ->
            val matchesQuery = cleanQuery.isEmpty() ||
                    food.name.lowercase().contains(cleanQuery) ||
                    food.regionalName.lowercase().contains(cleanQuery) ||
                    food.healthTags.any { it.lowercase().contains(cleanQuery) } ||
                    food.description.lowercase().contains(cleanQuery)

            val matchesRegion = region == null || region == IndianRegion.ALL || food.region == region
            val matchesDiet = dietaryType == null || food.dietaryType == dietaryType

            matchesQuery && matchesRegion && matchesDiet
        }
    }
